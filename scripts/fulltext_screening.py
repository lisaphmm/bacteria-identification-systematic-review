def text_features(rid):
    doc = pymupdf.open(os.path.join(PDF_DIR, rid + ".pdf"))
    t = "\n".join(p.get_text() for p in doc)
    m = [x.start() for x in re.finditer(r"\n\s*(references|bibliography|literature cited)\s*\n", t, re.I)]
    if m and m[-1] > len(t) * 0.4:
        t = t[: m[-1]]
    t = t.lower()
    return dict(dl=len(re.findall(DL, t)), shallow=len(re.findall(SHALLOW, t)), metric=len(re.findall(METRIC, t)))


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    rows = list(csv.DictReader(open(IN_CSV)))
    out = []
    for r in rows:
        rid = r["Record_ID"]
        f = text_features(rid)
        if rid in MANUAL_EXCLUDE:
            code, detail = MANUAL_EXCLUDE[rid]
            dec = "Exclude"
        elif f["dl"] < 5 and rid not in FORCE_INCLUDE:
            code = "E6"
            base = "shallow ML only (SVM/RF)" if f["shallow"] >= 5 else "no deep-learning model described"
            detail = base + ("; " + PREV_DETAIL[rid] if rid in PREV_DETAIL else "")
            dec = "Exclude"
        else:
            dec, code, detail = "Include", "", ""
        out.append({
            "Record_ID": rid, "Title": r["Title"], "Authors": r["Authors"], "Year": r["Year"],
            "Journal": r["Journal"], "DOI": r["DOI"],
            "FullText_Decision": dec, "Exclusion_code": code,
            "Exclusion_reason": CODES.get(code, ""), "Exclusion_detail": detail,
            "Agar_plate_colony_images": "Yes" if (dec == "Include" and rid in AGAR_PLATE) else ("No" if dec == "Include" else ""),
            "Flag": INCLUDE_FLAGS.get(rid, "") if dec == "Include" else "",
            "DL_term_count": f["dl"], "Shallow_ML_term_count": f["shallow"], "Metric_term_count": f["metric"],
        })
    cols = list(out[0].keys())
    with open(os.path.join(OUT_DIR, "fulltext_screening_decisions.csv"), "w", newline="", encoding="utf-8-sig") as fh:
        w = csv.DictWriter(fh, fieldnames=cols); w.writeheader(); w.writerows(out)
    inc = [o for o in out if o["FullText_Decision"] == "Include"]
    exc = [o for o in out if o["FullText_Decision"] == "Exclude"]
    cnt = collections.Counter(o["Exclusion_code"] for o in exc)
    lines = [f"Assessed in full text: {len(out)}", f"Excluded at full text: {len(exc)}", f"Included: {len(inc)}",
             f"  of which agar-plate colony images: {sum(o['Agar_plate_colony_images']=='Yes' for o in inc)}", "Exclusion reasons:"]
    lines += [f"  {c}: {n}  {CODES[c]}" for c, n in sorted(cnt.items())]
    open(os.path.join(OUT_DIR, "fulltext_prisma_counts.txt"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))
    with open(os.path.join(OUT_DIR, "included_after_fulltext.csv"), "w", newline="", encoding="utf-8-sig") as fh:
        w = csv.DictWriter(fh, fieldnames=cols); w.writeheader(); w.writerows(inc)


if __name__ == "__main__":
    main()
